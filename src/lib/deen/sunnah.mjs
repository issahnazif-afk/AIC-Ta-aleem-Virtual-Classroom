// The same sunnah for everyone in a level on a given day (the date in the student's own time zone)
export function sunnahOfDay(level, date = new Date()) {
  const list = SUNNAH.filter((s) => s.level <= level);
  const d = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return list[d % list.length];
}
